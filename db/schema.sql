-- 商品调价流水（市场调研 / 报价团队按 UTC 自然月保管）。
--
-- 分区策略：RANGE (changed_at)，每个 UTC 月一个分区，命名为
-- price_changes_YYYYMM。月分区尚未建立时，流水先写入默认分区
-- price_changes_default；之后由 POST /partitions/{month}/backfill
-- 原子补建月分区并迁移当月旧行。
--
-- 主键必须包含分区键；id 由父表 identity 统一发号，迁移时连同原 id
-- 一起搬运，绝不重新编号。默认分区永远保留：补建只迁移目标月份的
-- 旧行，其他月份保持原样。

-- 防御性兜底：外键引用 items。docker compose 会先执行 init.sql 建表并
-- 灌种子；若 API 单独连到空库启动，这里保证至少能建出空表，不会因
-- 缺少 items 而启动失败。
CREATE TABLE IF NOT EXISTS items (
    id    serial PRIMARY KEY,
    name  text NOT NULL,
    price numeric(10, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS price_changes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id    integer        NOT NULL REFERENCES items (id),
    changed_at timestamptz    NOT NULL,
    new_price  numeric(10, 2) NOT NULL CHECK (new_price > 0),
    created_at timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT price_changes_pk PRIMARY KEY (id, changed_at)
) PARTITION BY RANGE (changed_at);

-- 父表索引会自动复制到每个分区（含默认分区与之后补建的分区）。
CREATE INDEX IF NOT EXISTS price_changes_changed_at_idx
    ON price_changes (changed_at);
CREATE INDEX IF NOT EXISTS price_changes_item_changed_at_idx
    ON price_changes (item_id, changed_at);

-- 月分区未建时的兜底分区。
CREATE TABLE IF NOT EXISTS price_changes_default
    PARTITION OF price_changes DEFAULT;
